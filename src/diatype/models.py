"""Pydantic models for DiaType request/response data.

All models include strict validation, helpful error messages, and
domain-specific properties to ensure only valid diagram data flows
through the system.
"""

from __future__ import annotations

from typing import Any

from pydantic import BaseModel, Field, field_validator, model_validator


class DiagramRequest(BaseModel):
    """Request to generate or refine a diagram from natural language.

    The prompt is validated for reasonable length to prevent abuse and
    ensure the LLM receives focused instructions.
    """

    prompt: str = Field(
        ...,
        min_length=8,
        max_length=4000,
        description="Natural language description of the desired diagram or refinement instruction.",
        examples=["A user login flow with authentication service and database"],
    )

    diagram_type: str = Field(
        default="flowchart",
        pattern=r"^(flowchart|sequenceDiagram|classDiagram|stateDiagram|erDiagram|journey|gantt|pie|quadrantChart|requirementDiagram|mindmap|timeline|gitGraph|c4Diagram)$",
        description="Mermaid diagram type. Must be one of the supported Mermaid diagram kinds.",
        examples=["flowchart", "sequenceDiagram"],
    )

    @field_validator("prompt")
    @classmethod
    def strip_prompt(cls, v: str) -> str:
        """Remove excessive whitespace that could confuse the LLM."""
        cleaned = " ".join(v.strip().split())
        if len(cleaned) < 8:
            raise ValueError("Prompt must contain meaningful content after cleaning")
        return cleaned

    @model_validator(mode="after")
    def validate_request(self) -> DiagramRequest:
        """Additional cross-field validation."""
        if "mermaid" in self.prompt.lower() and len(self.prompt) < 30:
            # Encourage users to describe intent rather than syntax
            pass  # allowed but we could log a warning in production
        return self

    def __str__(self) -> str:
        return f"DiagramRequest(type={self.diagram_type}, prompt={self.prompt[:60]}...)"


class Diagram(BaseModel):
    """A complete diagram artifact containing Mermaid source, explanation, and optional SVG.

    All fields are validated to guarantee that the diagram can be rendered
    and explained back to the user.
    """

    mermaid: str = Field(
        ...,
        min_length=10,
        description="Valid Mermaid diagram syntax. Must start with a valid diagram keyword.",
        examples=["flowchart TD\n    A[Start] --> B[Process]"],
    )

    explanation: str = Field(
        ...,
        min_length=15,
        description="Plain-English explanation of the diagram generated by the LLM.",
    )

    svg: str = Field(
        default="",
        description="SVG markup of the rendered diagram. Empty until rendered by Mermaid.js.",
    )

    diagram_type: str = Field(
        default="flowchart",
        description="Detected or requested diagram type for reference.",
    )

    @field_validator("mermaid")
    @classmethod
    def validate_mermaid_starts_correctly(cls, v: str) -> str:
        """Ensure the Mermaid code begins with a recognized diagram directive.

        This is a lightweight syntactic sanity check before sending to the validator.
        """
        stripped = v.strip()
        valid_starts = (
            "flowchart",
            "graph",
            "sequenceDiagram",
            "classDiagram",
            "stateDiagram",
            "erDiagram",
            "journey",
            "gantt",
            "pie",
            "quadrantChart",
            "requirementDiagram",
            "mindmap",
            "timeline",
            "gitGraph",
            "c4Diagram",
        )
        if not any(stripped.startswith(start) for start in valid_starts):
            raise ValueError(
                "Mermaid code must start with a valid diagram type "
                "(flowchart, sequenceDiagram, classDiagram, ...)"
            )
        return stripped

    @model_validator(mode="after")
    def ensure_consistent_type(self) -> Diagram:
        """Derive diagram_type from the mermaid source if not explicitly set."""
        if not self.diagram_type or self.diagram_type == "flowchart":
            first_line = self.mermaid.split("\n", 1)[0].strip()
            for candidate in (
                "sequenceDiagram",
                "classDiagram",
                "stateDiagram",
                "erDiagram",
                "gantt",
                "pie",
                "mindmap",
            ):
                if candidate.lower() in first_line.lower():
                    self.diagram_type = candidate
                    break
            else:
                # default remains flowchart for TD/LR graphs
                if "graph " in first_line.lower() or "flowchart " in first_line.lower():
                    self.diagram_type = "flowchart"
        return self

    def is_renderable(self) -> bool:
        """Return True if this diagram has both source and (optionally) SVG."""
        return bool(self.mermaid and self.mermaid.strip())

    def to_markdown(self) -> str:
        """Return a Markdown code block suitable for embedding in docs."""
        return f"```mermaid\n{self.mermaid}\n```"

    def model_dump(self, **kwargs: Any) -> dict[str, Any]:
        """Override to always include computed fields and exclude None values by default."""
        kwargs.setdefault("exclude_none", True)
        return super().model_dump(**kwargs)

    def __repr__(self) -> str:
        return f"Diagram(type={self.diagram_type}, mermaid_len={len(self.mermaid)})"
